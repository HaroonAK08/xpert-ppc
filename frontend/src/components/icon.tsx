export type LucideIconName = keyof typeof icons;

/**
 * Renders a lucide icon by name so content stored in MongoDB can reference
 * icons as plain strings.
 */
export function Icon({
  name,
  ...props
}: LucideProps & { name: LucideIconName | (string & {}) }) {
  const Cmp = icons[name as LucideIconName] ?? Sparkles;
  return <Cmp {...props} />;
}

export default Icon;
